-- ============================================================
-- الخطوة 2 — تعديل الـ Schema (بعد الانتهاء من مراجعة الخطوة 1)
-- تُنفّذ داخل معاملة واحدة: حذف الفهرس القديم وإنشاء الجديد المركّب.
-- ============================================================
begin;

-- 2.1 حذف الفهرس الفريد العام القديم (كود الشحنة وحده)
drop index if exists public.idx_invoices_code;

-- 2.2 إنشاء فهرس فريد مركّب جديد (كود الشحنة + اليومية)
create unique index if not exists idx_invoices_code_daily
    on public.invoices using btree ("كود الشحنة", "اليومية");

commit;
