-- ============================================================
-- الخطوة 1 — تدقيق البيانات الحالية (راجع النتائج يدويًا قبل التعديل)
-- يكشف حالات الدمج القديمة الناتجة عن الفهرس الفريد القديم على الكود فقط.
-- ============================================================
select "كود الشحنة", count(*) as occurrences,
       array_agg(distinct "اليومية") as daily_values,
       array_agg(id) as row_ids
from public.invoices
where "كود الشحنة" is not null and "كود الشحنة" <> ''
group by "كود الشحنة"
having count(*) > 1
order by occurrences desc;

